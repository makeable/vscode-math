'use strict';
// Generates the TextMate injection grammars that make lines containing a sum
// taller. A token rule (configurationDefaults in package.json) gives the
// meta.mathview.tall scope a bigger line height.
//
// Grammars are static files that VS Code reads at startup, so the extension
// regenerates them when the notation settings change and offers a reload.

const { bigOpCallPattern } = require('./latex');

const TALL_SCOPE = 'meta.mathview.tall';

const GRAMMARS = {
  python: { file: 'syntaxes/mathview.python.json', scopeName: 'mathview.python', injectTo: ['source.python'] },
  julia: { file: 'syntaxes/mathview.julia.json', scopeName: 'mathview.julia', injectTo: ['source.julia'] },
};

// Regex sources that mark a line as tall. They use the subset of regex syntax
// that both Oniguruma (TextMate) and JavaScript understand, so the extension
// can run the same patterns to know which lines are tall.
function tallPatterns(notation) {
  const call = bigOpCallPattern(notation);
  if (!call) return [];
  // the name only (not the paren), and only when a "for" follows on the same line
  const name = call.replace(/\\s\*\\\($/, '');
  return [`${name}(?=\\s*\\([^\\n]*\\bfor\\b)`];
}

function buildGrammar(profile, notation) {
  const g = GRAMMARS[profile];
  const sources = g.injectTo.map(s => `L:${s} -comment -string`).join(', ');
  return {
    scopeName: g.scopeName,
    injectionSelector: sources,
    comment: 'Generated by Math View from its notation settings. Do not edit.',
    patterns: tallPatterns(notation).map(match => ({ match, name: `support.function.mathview ${TALL_SCOPE}` })),
  };
}

module.exports = { GRAMMARS, TALL_SCOPE, tallPatterns, buildGrammar };
